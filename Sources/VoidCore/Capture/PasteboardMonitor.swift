import Foundation
import AppKit
import Combine

public enum PauseDuration: String, CaseIterable, Sendable {
    case fifteenMinutes = "15 minutes"
    case thirtyMinutes = "30 minutes"
    case oneHour = "1 hour"
    case indefinitely = "Until resumed"

    public var seconds: TimeInterval? {
        switch self {
        case .fifteenMinutes: return 15 * 60
        case .thirtyMinutes: return 30 * 60
        case .oneHour: return 60 * 60
        case .indefinitely: return nil
        }
    }
}

public final class PasteboardMonitor: ObservableObject, @unchecked Sendable {
    public static let shared = PasteboardMonitor()

    public static let confidentialPasteboardTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "com.agilebits.onepassword",
        "com.bitwarden.confidential"
    ]

    public static let transientPasteboardTypes: Set<String> = [
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping"
    ]

    @Published public private(set) var isPaused: Bool = false
    @Published public private(set) var pauseResumeDate: Date? = nil

    private let pasteboard: NSPasteboard
    private let database: DatabaseManager
    private let assetStore: AssetStore
    private let settings: VoidSettings
    private var pollTimer: Timer?
    private var resumeTimer: Timer?
    private var lastChangeCount: Int
    private var suppressedChangeCount: Int?

    public var onItemCaptured: ((ClipboardItem) -> Void)?
    public var onMetadataEnriched: (() -> Void)?

    public init(
        pasteboard: NSPasteboard = .general,
        database: DatabaseManager = .shared,
        assetStore: AssetStore = .shared,
        settings: VoidSettings = .shared
    ) {
        self.pasteboard = pasteboard
        self.database = database
        self.assetStore = assetStore
        self.settings = settings
        self.lastChangeCount = pasteboard.changeCount
    }

    public func startMonitoring(interval: TimeInterval = 0.2) {
        stopMonitoring()
        lastChangeCount = pasteboard.changeCount
        DispatchQueue.main.async { [weak self] in
            self?.pollTimer = Timer.scheduledTimer(withTimeInterval: interval, repeats: true) { [weak self] _ in
                self?.checkPasteboard()
            }
        }
    }

    public func stopMonitoring() {
        pollTimer?.invalidate()
        pollTimer = nil
    }

    public func markInternalWrite(changeCount: Int) {
        suppressedChangeCount = changeCount
        lastChangeCount = changeCount
    }

    public func pause(for duration: PauseDuration) {
        resumeTimer?.invalidate()
        isPaused = true
        if let seconds = duration.seconds {
            let targetDate = Date().addingTimeInterval(seconds)
            pauseResumeDate = targetDate
            resumeTimer = Timer.scheduledTimer(withTimeInterval: seconds, repeats: false) { [weak self] _ in
                self?.resume()
            }
        } else {
            pauseResumeDate = nil
        }
    }

    public func resume() {
        resumeTimer?.invalidate()
        resumeTimer = nil
        isPaused = false
        pauseResumeDate = nil
        lastChangeCount = pasteboard.changeCount
    }

    public func shouldIgnorePasteboard(
        types: [String],
        sourceBundleID: String?
    ) -> Bool {
        if isPaused {
            return true
        }
        if let bundleID = sourceBundleID {
            if bundleID == Bundle.main.bundleIdentifier || bundleID == "com.voidapp.mac" {
                return true
            }
            if settings.ignoredAppBundleIDs.contains(bundleID) {
                return true
            }
        }
        let typeSet = Set(types)
        if settings.ignoreConfidentialContent && !typeSet.isDisjoint(with: Self.confidentialPasteboardTypes) {
            return true
        }
        if settings.ignoreTransientContent && !typeSet.isDisjoint(with: Self.transientPasteboardTypes) {
            return true
        }
        return false
    }

    public func checkPasteboard() {
        let currentCount = pasteboard.changeCount
        guard currentCount != lastChangeCount else { return }
        lastChangeCount = currentCount

        if suppressedChangeCount == currentCount {
            return
        }

        let frontApp = NSWorkspace.shared.frontmostApplication
        let sourceBundleID = frontApp?.bundleIdentifier
        let sourceAppName = frontApp?.localizedName
        let rawTypes = (pasteboard.types ?? []).map(\.rawValue)

        guard !shouldIgnorePasteboard(types: rawTypes, sourceBundleID: sourceBundleID) else {
            return
        }

        let colorHex = AppIconColorExtractor.shared.colorHex(
            forBundleID: sourceBundleID,
            appURL: frontApp?.bundleURL
        )

        guard let classified = PayloadClassifier.classifyPasteboard(
            pasteboard,
            sourceAppBundleID: sourceBundleID,
            sourceAppName: sourceAppName,
            sourceAppColorHex: colorHex,
            assetStore: assetStore
        ) else {
            return
        }

        let savedItem = database.insertOrPromoteItem(classified, deduplicateConsecutive: true)

        if settings.soundEffects {
            NSSound(named: NSSound.Name("Tink"))?.play()
        }

        onItemCaptured?(savedItem)

        // Asynchronous OCR & Link Preview enrichment
        if savedItem.contentType == .image, let imageHash = savedItem.imageAssetHash {
            VisionOCRService.shared.enrichImageItemAsync(
                itemID: savedItem.id,
                imageHash: imageHash,
                database: database,
                assetStore: assetStore
            ) { [weak self] in
                DispatchQueue.main.async {
                    self?.onMetadataEnriched?()
                }
            }
        } else if savedItem.contentType == .link, let urlStr = savedItem.urlString {
            LinkMetadataService.shared.enrichLinkItem(
                itemID: savedItem.id,
                urlString: urlStr,
                database: database,
                assetStore: assetStore,
                settings: settings
            ) { [weak self] in
                DispatchQueue.main.async {
                    self?.onMetadataEnriched?()
                }
            }
        }
    }

    @discardableResult
    public func createManualTextItem(
        text: String,
        title: String? = nil,
        pinboardID: String? = nil
    ) -> ClipboardItem {
        var item = PayloadClassifier.classifyString(
            text,
            title: title,
            sourceAppBundleID: "com.voidapp.mac",
            sourceAppName: "Void",
            sourceAppColorHex: "#FF9400",
            assetStore: assetStore
        )
        item.pinboardID = pinboardID
        let saved = database.insertOrPromoteItem(item, deduplicateConsecutive: false)
        onItemCaptured?(saved)
        return saved
    }
}
